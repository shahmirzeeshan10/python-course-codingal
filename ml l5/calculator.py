def add(x, y):
    return x+y
def subtract(x,y):
    return x-y
def multiply(x,y):
    return x*y
def divide(x,y):
    return x/y

number1=int(input("enter your first number"))
number2 = int(input("enter your second number"))
print("the sum of 2 numbers is ",add(number1,number2))
print("the subtraction of 2 numbers is ",subtract(number1,number2))
print("the product of 2 numbers is ",multiply(number1,number2))
print("the division of 2 numbers is ",divide(number1,number2))


