from tkinter import *
window=Tk()
window.title("my profile card")
window.geometry("300x400")
Label(window, text="my profile card",bg ="blue",fg="black").grid(row=0,column=0,columnspan=2)
name_label=Label(window,text="Name:").grid(row=1,column=0,columnspan=2)
name_entry=Entry(window,bg="light yellow").grid(row=1,column=2)
hobby_label=Label(window,text="Hobby:").grid(row=2,column=0,columnspan=2)
hobby_entry=Entry(window,bg="light yellow").grid(row=2,column=2)
frame=Frame(window,relief=RAISED,borderwidth=3)
frame.grid(row=3,column=1,columnspan=2)
about_label=Label(frame,text="About Me:").pack()
about_text=Text(frame,width=35,height=4,bg="light yellow").pack()
Button1=Button(window,text="show my card",bg="purple",fg="white").grid(row=4,column=0,columnspan=2)
window.mainloop()